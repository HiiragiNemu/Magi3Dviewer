export function getCharacterTrilingualName(
    id: string | number,
    fallback: string,
): TrilingualCharacterName {
    return characterTrilingualNames[String(id) as keyof typeof characterTrilingualNames] ?? {
        zh: fallback,
        ja: fallback,
        romaji: fallback,
    }
}

export function formatCharacterTrilingualName(id: string | number, fallback: string): string {
    const name = getCharacterTrilingualName(id, fallback)
    return [...new Set([name.zh, name.ja, name.romaji].map(value => value.trim()).filter(Boolean))].join(' / ')
}
